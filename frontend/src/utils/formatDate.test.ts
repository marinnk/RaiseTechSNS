import { describe, expect, it } from 'vitest';
import { formatDate } from './formatDate';

describe('formatDate', () => {
  it('オフセット付きのISO日時文字列を日付だけの表示にフォーマットする', () => {
    expect(formatDate('2026-08-10T03:00:00+09:00')).toBe('2026-08-10');
  });

  it('ブラウザのローカルタイムゾーンが異なっていても同じ瞬間なら同じ日付になる', () => {
    // UTCで2026-08-09T23:00:00Zは、+09:00（日本時間）では2026-08-10T08:00:00
    const isoInUtc = '2026-08-09T23:00:00Z';
    const isoInJst = '2026-08-10T08:00:00+09:00';

    // 実行環境（テスト環境）のローカルタイムゾーンに関わらず、
    // 同じ瞬間を指す2つの文字列は同じフォーマット結果になるはず
    expect(formatDate(isoInUtc)).toBe(formatDate(isoInJst));
  });

  it('オフセット無しの日時文字列（タイムゾーン依存の旧バックエンド仕様）だとブラウザのローカルタイムとして解釈される', () => {
    // このテストは回帰防止用のドキュメントを兼ねる：
    // オフセット無し文字列は`new Date()`によってbrowser local timeとして解釈されるため、
    // サーバー・ブラウザのタイムゾーンが異なると表示がずれる（#17で解消した問題そのもの）。
    // バックエンドが必ずオフセット付き文字列を返す限りこの分岐は実行されないが、
    // formatDate自体はオフセット無し文字列も（ローカルタイムとして）フォーマットできることを確認する。
    expect(formatDate('2026-08-10T12:00:00')).toBe('2026-08-10');
  });
});
